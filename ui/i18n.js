  let currentLang = "zh-TW";

  function normalizeLang(lang) {
    if (SUPPORTED.includes(lang)) return lang;
    return "zh-TW";
  }

  function t(key, vars = {}, langOverride = null) {
    const lang = langOverride ? normalizeLang(langOverride) : currentLang;
    const table = DICT[lang] || DICT["zh-TW"];
    let str = table[key] !== undefined ? table[key] : DICT["zh-TW"][key];
    if (str === undefined) return key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replaceAll(`{${k}}`, String(v ?? ""));
      }
    }
    return str;
  }

  function applyI18n(lang) {
    currentLang = normalizeLang(lang);
    document.documentElement.lang = HTML_LANG[currentLang] || "zh-Hant";
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      const k = node.getAttribute("data-i18n");
      if (!k) return;
      const val = t(k);
      node.textContent = val;
      if (node.tagName === "OPTION") {
        node.label = val;
      }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      const k = node.getAttribute("data-i18n-placeholder");
      if (k) node.placeholder = t(k);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => {
      const k = node.getAttribute("data-i18n-title");
      if (k) node.title = t(k);
    });
    document.querySelectorAll("select").forEach((sel) => {
      const v = sel.value;
      sel.value = "";
      sel.value = v;
    });
  }

  window.NYX_I18N = {
    SUPPORTED,
    normalizeLang,
    t,
    applyI18n,
  };
